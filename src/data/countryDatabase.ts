export type GlobeLayerId =
  | 'geographic'
  | 'terrain'
  | 'political'
  | 'night'
  | 'choropleth'
  | 'hologram';

export type ChoroplethMetric =
  | 'gdpPerCapita'
  | 'populationDensity'
  | 'gdpNominalB'
  | 'hdi'
  | 'areaKm2';

export interface CountryStats {
  id: string; // ISO 3166-1 numeric string (matches world-atlas id)
  iso3: string;
  name: string;
  flag: string;
  region: string;
  subregion: string;
  capital: string;
  capitalCoords: [number, number]; // [lng, lat]
  areaKm2: number;
  population: number;
  gdpNominalB: number; // Billions USD
  gdpPppB: number; // Billions USD (PPP)
  gdpPerCapita: number; // USD
  gdpPppPerCapita: number; // USD
  hdi: number; // 0 - 1
  lifeExpectancy: number; // years
  medianAge: number; // years
  urbanizationPct: number; // %
  coastlineKm: number;
  highestPeakName: string;
  highestPeakM: number;
  forestPct: number;
  avgTempC: number;
  co2PerCapitaT: number;
  costOfLivingIndex: number; // NYC = 100, Global avg ~55
  currency: string;
  drivingSide: 'Left' | 'Right';
  timeZone: string;
  topExports: string[];
  funFact: string;
  /**
   * `estimated` profiles are synthesized for world-atlas countries that have
   * no hand-written entry. Their spherical land area is measured. Population,
   * GDP, HDI, peaks, coastline, and currency are not.
   */
  dataQuality?: 'curated' | 'estimated';
}

/** True when vital figures other than spherical land area were not researched. */
export function isEstimatedProfile(stats: CountryStats): boolean {
  return stats.dataQuality === 'estimated';
}

